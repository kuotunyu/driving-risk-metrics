def degrade(
    target: np.ndarray,
    profile: DegradationProfile,
    rng: np.random.Generator | None = None,
    ignore_index: int = IGNORE_INDEX,
) -> np.ndarray:
    """Produce a synthetic prediction from a ground-truth mask.

    Void pixels are passed through unchanged; they are excluded from every
    metric anyway, and inventing predictions for them would only obscure that.
    """
    if rng is None:
        rng = np.random.default_rng(0)

    target = np.asarray(target)
    pred = target.copy()
    void = target == ignore_index

    for cls in profile.drop:
        pred[target == cls] = profile.fill_for(cls)

    for cls, k in profile.erode.items():
        if cls in profile.drop or k <= 0:
            continue
        mask = target == cls
        if not mask.any():
            continue
        kept = _erode(mask, k)
        pred[mask & ~kept] = profile.fill_for(cls)

    for cls, k in profile.dilate.items():
        if k <= 0:
            continue
        mask = target == cls
        if not mask.any():
            continue
        grown = _dilate(mask, k) & ~void
        pred[grown] = cls

    if profile.noise > 0:
        flip = (rng.random(target.shape) < profile.noise) & ~void
        pred[flip] = rng.integers(0, NUM_CLASSES, size=int(flip.sum()))

    pred[void] = target[void]
    return pred.astype(target.dtype)


def profile_summary() -> list[dict]:
    """Machine-readable description of each profile, for the report."""
    return [
        {
            "name": p.name,
            "description": p.description,
            "dropped_classes": [CLASS_NAMES[c] for c in p.drop],
            "eroded_classes": {CLASS_NAMES[c]: k for c, k in p.erode.items()},
            "dilated_classes": {CLASS_NAMES[c]: k for c, k in p.dilate.items()},
            "noise": p.noise,
            "synthetic": True,
        }
        for p in PROFILES.values()
    ]
