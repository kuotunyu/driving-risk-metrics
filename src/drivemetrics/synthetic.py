        erode={_POLE: 1, _SIGN: 1, _PED: 1, _BIC: 1, _CAR: 1, _BUILDING: 2, _ROAD: 1},
        confused_with={_POLE: _BUILDING, _SIGN: _BUILDING, _PED: _BUILDING},
